def roster_text(roster):
    lines = []
    for e in roster:
        tag = "일할 수 있음" if e["active"] else "아직 준비 중(일을 맡길 수 없음)"
        lines.append("- %s (%s): %s [%s]" % (e["name"], e["team"], e["role"], tag))
    return "\n".join(lines)


